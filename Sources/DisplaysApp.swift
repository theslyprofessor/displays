// MARK: - Self-Hosted Ed25519 Offline License Verifier (MusicMind × Build Forward Tech)

struct LicensePayload: Codable, Equatable {
    let v: Int
    let p: String
    let e: String
    let t: String
    let s: Int
    let iat: Int
}

enum LicenseVerifier {
    /// Embedded 32-byte raw Ed25519 public key generated by `musicmind-license`
    static let publicKeyBase64 = "lKfWuwe6m2o92MiIRoKZOf3u41hxthu9mO7m7oRa8vY="

    static var licenseFileURL: URL {
        FileManager.default.homeDirectoryForCurrentUser
            .appendingPathComponent(".config/displays/license.key")
            .resolvingSymlinksInPath()
    }

    static func decodeBase64URL(_ input: String) -> Data? {
        var b64 = input
            .replacingOccurrences(of: "-", with: "+")
            .replacingOccurrences(of: "_", with: "/")
        let rem = b64.count % 4
        if rem > 0 {
            b64.append(String(repeating: "=", count: 4 - rem))
        }
        return Data(base64Encoded: b64)
    }

    static func verify(_ rawKey: String) -> LicensePayload? {
        let trimmed = rawKey.trimmingCharacters(in: .whitespacesAndNewlines)
        guard trimmed.hasPrefix("MM1-") else { return nil }
        let parts = trimmed.dropFirst(4).split(separator: ".", maxSplits: 1).map(String.init)
        guard parts.count == 2,
              let pubData = Data(base64Encoded: publicKeyBase64),
              let sigData = decodeBase64URL(parts[1]),
              let payloadData = decodeBase64URL(parts[0]),
              let pubKey = try? Curve25519.Signing.PublicKey(rawRepresentation: pubData)
        else { return nil }

        guard pubKey.isValidSignature(sigData, for: Data(parts[0].utf8)) else {
            return nil
        }
        return try? JSONDecoder().decode(LicensePayload.self, from: payloadData)
    }

    static func loadVerifiedLicense() -> LicensePayload? {
        guard let str = try? String(contentsOf: licenseFileURL, encoding: .utf8) else {
            return nil
        }
        return verify(str)
    }

    static func saveLicenseKey(_ rawKey: String) -> LicensePayload? {
        guard let payload = verify(rawKey) else { return nil }
        let trimmed = rawKey.trimmingCharacters(in: .whitespacesAndNewlines)
        let dir = licenseFileURL.deletingLastPathComponent()
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        try? trimmed.write(to: licenseFileURL, atomically: true, encoding: .utf8)
        return payload
    }
}

// MARK: - Models

enum DisplayRole: String, CaseIterable, Codable, Identifiable {
    case main = "main"
    case mirrorMain = "mirror_main"
    case extendRight = "extend_right"
    case extendLeft = "extend_left"
    case off = "off"

    var id: String { rawValue }

    var label: String {
        switch self {
        case .main: return "Main (Primary)"
        case .mirrorMain: return "Mirror Main"
        case .extendRight: return "Extend Right"
        case .extendLeft: return "Extend Left"
        case .off: return "Off (Muted)"
        }
    }
}

struct ConnectedDisplay: Identifiable, Equatable {
    let id: String          // Persistent UUID from displayplacer / CoreGraphics
    let cgID: UInt32        // Contextual CGDirectDisplayID
    let name: String        // Hardware / resolved name
    let typeLabel: String   // e.g. "27 inch external screen"
    let resolution: String  // e.g. "1920x1080"
    let hz: Int             // e.g. 75, 120, 60
    let scaling: Bool
    let enabled: Bool
    let isMain: Bool
    let isBuiltIn: Bool
    let mirrorMasterID: UInt32
}

struct MonitorRecord: Identifiable, Codable, Equatable {
    var id: String              // Persistent UUID (or custom ID for historical reference monitors)
    var label: String           // Short user-editable name, e.g. "C27-30 (2)", "Room TV", "MacBook"
    var note: String            // User-editable context/history note, e.g. "Main Desk", "In separate room", "On Studio A Mac"
    var icon: String            // "display", "tv.fill", "laptopcomputer"
    var ignoredInSpace: Bool    // If true, hide from preset chips in this space (e.g. laptop in separate room)
}

struct DisplayPreset: Identifiable, Codable, Equatable {
    var id: String
    var name: String
    var subtitle: String
    var icon: String
    /// Either a literal `displayplacer "..."` command or a dynamic template:
    /// - `@dynamic:mirror_all`
    /// - `@dynamic:extend_all`
    /// - `@dynamic:laptop_only`
    /// - `@dynamic:broadcast_main_extend_builtin`
    var command: String
}

struct MachineFolder: Identifiable, Codable, Equatable {
    var id: String
    var name: String
    var description: String
    var signatureUUIDs: [String]
    var displayAliases: [String: String]
    var monitors: [MonitorRecord]?
    var presets: [DisplayPreset]

    var resolvedMonitors: [MonitorRecord] {
        if let m = monitors, !m.isEmpty {
            return m
        }
        return displayAliases.sorted(by: { $0.value < $1.value }).map { (uuid, alias) in
            let lower = alias.lowercased()
            let icon = lower.contains("macbook") || lower.contains("laptop")
                ? "laptopcomputer"
                : (lower.contains("tv") || lower.contains("blackmagic") || lower.contains("extron") || lower.contains("broadcast") ? "tv.fill" : "display")
            return MonitorRecord(id: uuid, label: alias, note: "", icon: icon, ignoredInSpace: false)
        }
    }
}

struct PresetsRoot: Codable, Equatable {
    var version: Int = 3
    var selectedFolderID: String
    var lastAppliedPresetID: String?
    var folders: [MachineFolder]
}

// MARK: - Default Seed Data (General User / New Machine vs Stowed Config)

enum SeedData {
    static let mbpUUID = "37D8832A-2D66-02CA-B9F7-8F30A301B230"

    /// When a brand-new user or single-room desktop (like Studio A Mac without dotfiles)
    /// launches the app with no ~/.config/displays/presets.json, create a clean single-space
    /// setup based on the machine's actual hostname and connected displays.
    static func defaultRootForNewMachine() -> PresetsRoot {
        let host = Host.current().localizedName ?? "This Mac"
        let defaultFolder = MachineFolder(
            id: "default-space",
            name: host,
            description: "Default display presets for \(host) (click ✎ to edit description or monitors)",
            signatureUUIDs: [],
            displayAliases: [:],
            monitors: [],
            presets: [
                DisplayPreset(
                    id: "default-mirror-all",
                    name: "Mirror All Displays",
                    subtitle: "All connected monitors show the same screen",
                    icon: "rectangle.on.rectangle.circle.fill",
                    command: "@dynamic:mirror_all"
                ),
                DisplayPreset(
                    id: "default-extend-all",
                    name: "Extend All Displays Side-by-Side",
                    subtitle: "Each connected monitor is a separate extended desktop",
                    icon: "rectangle.split.3x1.fill",
                    command: "@dynamic:extend_all"
                ),
                DisplayPreset(
                    id: "default-primary-only",
                    name: "Primary Display Only (Mute Secondary Screens)",
                    subtitle: "Turns off secondary/TV displays for privacy",
                    icon: "eye.slash.fill",
                    command: "@dynamic:laptop_only"
                ),
            ]
        )
        return PresetsRoot(
            version: 3,
            selectedFolderID: defaultFolder.id,
            lastAppliedPresetID: nil,
            folders: [defaultFolder]
        )
    }
}

// MARK: - Store

@MainActor
final class DisplayStore: ObservableObject {
    static let shared = DisplayStore()
    @Published var root: PresetsRoot
    @Published var connected: [ConnectedDisplay] = []
    @Published var currentCommand: String = ""
    @Published var detectedFolderID: String? = nil
    @Published var roleDraft: [String: DisplayRole] = [:]
    @Published var busy: Bool = false
    @Published var statusMessage: String? = nil
    @Published var errorMessage: String? = nil

    static let configDir = URL(fileURLWithPath: NSHomeDirectory() + "/.config/displays")
    static let configFile = configDir.appendingPathComponent("presets.json")

    init() {
        self.root = DisplayStore.loadOrSeed()
        refreshDisplays()
    }

    static func loadOrSeed() -> PresetsRoot {
        if let data = try? Data(contentsOf: configFile),
           let decoded = try? JSONDecoder().decode(PresetsRoot.self, from: data),
           !decoded.folders.isEmpty {
            return decoded
        }
        let seeded = SeedData.defaultRootForNewMachine()
        saveRoot(seeded)
        return seeded
    }

    static func saveRoot(_ r: PresetsRoot) {
        try? FileManager.default.createDirectory(at: configDir, withIntermediateDirectories: true)
        let enc = JSONEncoder()
        enc.outputFormatting = [.prettyPrinted, .sortedKeys]
        if let data = try? enc.encode(r) {
            let targetURL = configFile.resolvingSymlinksInPath()
            try? data.write(to: targetURL, options: .atomic)
        }
    }

    func save() {
        DisplayStore.saveRoot(root)
    }

    var selectedFolderIndex: Int? {
        root.folders.firstIndex(where: { $0.id == root.selectedFolderID }) ?? (root.folders.isEmpty ? nil : 0)
    }

    var selectedFolder: MachineFolder? {
        guard let idx = selectedFolderIndex else { return nil }
        return root.folders[idx]
    }

    // MARK: - Inspect Live Screens

    nonisolated static func runCommand(_ exe: String, _ args: [String]) -> (Int32, String, String) {
        let p = Process()
        p.executableURL = URL(fileURLWithPath: exe)
        p.arguments = args
        var env = ProcessInfo.processInfo.environment
        let home = NSHomeDirectory()
        env["PATH"] = "/opt/homebrew/bin:\(home)/.nix-profile/bin:\(home)/.local/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
        p.environment = env
        let out = Pipe(), err = Pipe()
        p.standardOutput = out
        p.standardError = err
        p.standardInput = FileHandle.nullDevice
        do {
            try p.run()
        } catch {
            return (127, "", "\(error)")
        }
        let o = out.fileHandleForReading.readDataToEndOfFile()
        let e = err.fileHandleForReading.readDataToEndOfFile()
        p.waitUntilExit()
        return (
            p.terminationStatus,
            String(decoding: o, as: UTF8.self),
            String(decoding: e, as: UTF8.self)
        )
    }

    nonisolated static func fetchSystemProfilerNames() -> [UInt32: String] {
        let (rc, out, _) = runCommand("/usr/sbin/system_profiler", ["SPDisplaysDataType", "-json"])
        guard rc == 0,
              let data = out.data(using: .utf8),
              let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let gpus = json["SPDisplaysDataType"] as? [[String: Any]] else {
            return [:]
        }
        var map: [UInt32: String] = [:]
        for gpu in gpus {
            guard let ndrvs = gpu["spdisplays_ndrvs"] as? [[String: Any]] else { continue }
            for d in ndrvs {
                if let idStr = d["_spdisplays_displayID"] as? String,
                   let cgID = UInt32(idStr),
                   let rawName = d["_name"] as? String {
                    let cleanName = (rawName == "Color LCD") ? "MacBook Pro" : rawName
                    map[cgID] = cleanName
                }
            }
        }
        return map
    }

    nonisolated static func parseDisplayplacerList(namesByCGID: [UInt32: String], aliases: [String: String]) -> ([ConnectedDisplay], String) {
        let (_, out, _) = runCommand("/usr/bin/env", ["displayplacer", "list"])
        var displays: [ConnectedDisplay] = []
        var finalCmd = ""

        var currentUUID = ""
        var currentCGID: UInt32 = 0
        var currentType = ""
        var currentRes = "1920x1080"
        var currentHz = 60
        var currentScaling = false
        var currentEnabled = true
        var currentMain = false

        func flushBlock() {
            guard !currentUUID.isEmpty else { return }
            let isBuiltIn = currentType.localizedCaseInsensitiveContains("MacBook") || CGDisplayIsBuiltin(currentCGID) != 0
            let mirrorMaster = CGDisplayMirrorsDisplay(currentCGID)
            let spName = namesByCGID[currentCGID]
            let alias = aliases[currentUUID]
            let displayName = alias ?? spName ?? (isBuiltIn ? "MacBook Pro" : currentType)
            displays.append(ConnectedDisplay(
                id: currentUUID,
                cgID: currentCGID,
                name: displayName,
                typeLabel: currentType,
                resolution: currentRes,
                hz: currentHz,
                scaling: currentScaling,
                enabled: currentEnabled,
                isMain: currentMain || (CGDisplayIsMain(currentCGID) != 0),
                isBuiltIn: isBuiltIn,
                mirrorMasterID: mirrorMaster
            ))
            currentUUID = ""
            currentCGID = 0
            currentType = ""
            currentRes = "1920x1080"
            currentHz = 60
            currentScaling = false
            currentEnabled = true
            currentMain = false
        }

        for rawLine in out.components(separatedBy: .newlines) {
            let line = rawLine.trimmingCharacters(in: .whitespaces)
            if line.hasPrefix("Persistent screen id:") {
                flushBlock()
                currentUUID = line.replacingOccurrences(of: "Persistent screen id:", with: "").trimmingCharacters(in: .whitespaces)
            } else if line.hasPrefix("Contextual screen id:") {
                let s = line.replacingOccurrences(of: "Contextual screen id:", with: "").trimmingCharacters(in: .whitespaces)
                currentCGID = UInt32(s) ?? 0
            } else if line.hasPrefix("Type:") {
                currentType = line.replacingOccurrences(of: "Type:", with: "").trimmingCharacters(in: .whitespaces)
            } else if line.hasPrefix("Resolution:") {
                currentRes = line.replacingOccurrences(of: "Resolution:", with: "").trimmingCharacters(in: .whitespaces)
            } else if line.hasPrefix("Hertz:") {
                let s = line.replacingOccurrences(of: "Hertz:", with: "").trimmingCharacters(in: .whitespaces)
                currentHz = Int(s) ?? 60
            } else if line.hasPrefix("Scaling:") {
                currentScaling = line.localizedCaseInsensitiveContains("on")
            } else if line.hasPrefix("Enabled:") {
                currentEnabled = line.localizedCaseInsensitiveContains("true")
            } else if line.hasPrefix("Origin:") {
                currentMain = line.localizedCaseInsensitiveContains("main display")
            } else if line.hasPrefix("displayplacer ") {
                finalCmd = line
            }
        }
        flushBlock()
        return (displays, finalCmd)
    }

    func refreshDisplays() {
        var allAliases: [String: String] = [:]
        for f in root.folders {
            for (k, v) in f.displayAliases { allAliases[k] = v }
            for m in f.resolvedMonitors { allAliases[m.id] = m.label }
        }
        Task {
            let result = await Task.detached { () -> ([ConnectedDisplay], String) in
                let names = DisplayStore.fetchSystemProfilerNames()
                return DisplayStore.parseDisplayplacerList(namesByCGID: names, aliases: allAliases)
            }.value

            let (list, cmd) = result
            self.connected = list
            self.currentCommand = cmd

            var newRoles: [String: DisplayRole] = [:]
            let mainDisp = list.first(where: { $0.isMain }) ?? list.first
            for d in list {
                if !d.enabled {
                    newRoles[d.id] = .off
                } else if d.id == mainDisp?.id {
                    newRoles[d.id] = .main
                } else if d.mirrorMasterID != 0 {
                    newRoles[d.id] = .mirrorMain
                } else {
                    newRoles[d.id] = .extendRight
                }
            }
            self.roleDraft = newRoles

            // Auto-detect folder by matching connected external UUIDs against folder signatureUUIDs
            let connectedSet = Set(list.map(\.id))
            var bestFolder: String? = nil
            var bestScore = 0
            for folder in self.root.folders {
                let overlap = Set(folder.signatureUUIDs).intersection(connectedSet).count
                if overlap > bestScore {
                    bestScore = overlap
                    bestFolder = folder.id
                }
            }
            if let detected = bestFolder, self.detectedFolderID != detected {
                self.detectedFolderID = detected
                self.root.selectedFolderID = detected
                self.save()
            } else {
                self.detectedFolderID = bestFolder
            }

            // Auto-record any newly connected monitor into the active/detected space's monitor history
            if let targetID = bestFolder ?? (self.root.folders.count == 1 ? self.root.folders.first?.id : nil),
               let fIdx = self.root.folders.firstIndex(where: { $0.id == targetID }) {
                var mons = self.root.folders[fIdx].resolvedMonitors
                var changed = false
                for d in list {
                    if !mons.contains(where: { $0.id == d.id }) {
                        let icon = d.isBuiltIn ? "laptopcomputer" : (d.name.localizedCaseInsensitiveContains("TV") || d.name.localizedCaseInsensitiveContains("Blackmagic") ? "tv.fill" : "display")
                        mons.append(MonitorRecord(
                            id: d.id,
                            label: d.name,
                            note: d.isBuiltIn ? "Built-in" : "\(d.resolution) @ \(d.hz)Hz",
                            icon: icon,
                            ignoredInSpace: false
                        ))
                        changed = true
                    }
                }
                if changed {
                    self.root.folders[fIdx].monitors = mons
                    self.save()
                }
            }
        }
    }

    // MARK: - Build & Execute displayplacer Commands

    func resolveCommand(_ raw: String) -> String {
        let active = connected
        guard !active.isEmpty else { return "" }

        let builtIn = active.first(where: { $0.isBuiltIn })
        let externals = active.filter { !$0.isBuiltIn }

        if raw.hasPrefix("@dynamic:") {
            let mode = raw.replacingOccurrences(of: "@dynamic:", with: "")
            switch mode {
            case "mirror_all":
                let ordered = (externals + (builtIn.map { [$0] } ?? [])).map(\.id)
                let joined = ordered.joined(separator: "+")
                return #"displayplacer "id:\#(joined) res:1920x1080 enabled:true scaling:off origin:(0,0) degree:0""#

            case "extend_all":
                var parts: [String] = []
                var x = 0
                let ordered = (builtIn.map { [$0] } ?? []) + externals
                for d in ordered {
                    let res = d.isBuiltIn ? "1728x1117" : "1920x1080"
                    let width = d.isBuiltIn ? 1728 : 1920
                    let scale = d.isBuiltIn ? "on" : "off"
                    parts.append(#""id:\#(d.id) res:\#(res) enabled:true scaling:\#(scale) origin:(\#(x),0) degree:0""#)
                    x += width
                }
                return "displayplacer " + parts.joined(separator: " ")

            case "broadcast_main_extend_builtin":
                var parts: [String] = []
                if !externals.isEmpty {
                    let extIDs = externals.map(\.id).joined(separator: "+")
                    parts.append(#""id:\#(extIDs) res:1920x1080 enabled:true scaling:off origin:(0,0) degree:0""#)
                }
                if let mbp = builtIn {
                    let x = externals.isEmpty ? 0 : 1920
                    parts.append(#""id:\#(mbp.id) res:1728x1117 enabled:true scaling:on origin:(\#(x),0) degree:0""#)
                }
                return "displayplacer " + parts.joined(separator: " ")

            case "laptop_only":
                var parts: [String] = []
                if let mbp = builtIn {
                    parts.append(#""id:\#(mbp.id) res:1728x1117 hz:120 color_depth:8 enabled:true scaling:on origin:(0,0) degree:0""#)
                } else if let firstExt = externals.first {
                    parts.append(#""id:\#(firstExt.id) res:1920x1080 enabled:true scaling:off origin:(0,0) degree:0""#)
                }
                for ext in (builtIn != nil ? externals : Array(externals.dropFirst())) {
                    parts.append(#""id:\#(ext.id) enabled:false""#)
                }
                return "displayplacer " + parts.joined(separator: " ")

            default:
                return raw
            }
        }

        // Map symbolic placeholder IDs (e.g. POWAY-DESK-MONITOR, POWAY-KVM-TV) to connected external displays
        // and strip any unplugged UUIDs so multi-monitor presets still apply cleanly when a secondary screen is unplugged.
        let connectedIDs = Set(active.map(\.id))
        var availableExternals = externals.map(\.id).filter { !raw.contains($0) }
        var placeholderMap: [String: String] = [:]

        let pattern = #""([^"]+)""#
        guard let regex = try? NSRegularExpression(pattern: pattern) else { return raw }
        let nsRange = NSRange(raw.startIndex..<raw.endIndex, in: raw)
        let matches = regex.matches(in: raw, range: nsRange)
        if matches.isEmpty { return raw }

        var resolvedSegments: [String] = []
        for m in matches {
            guard let r = Range(m.range(at: 1), in: raw) else { continue }
            let seg = String(raw[r])
            var tokens = seg.split(separator: " ").map(String.init)
            guard let idIdx = tokens.firstIndex(where: { $0.hasPrefix("id:") }) else { continue }
            let rawIDList = tokens[idIdx].replacingOccurrences(of: "id:", with: "").split(separator: "+").map(String.init)

            var liveIDs: [String] = []
            for id in rawIDList {
                if connectedIDs.contains(id) {
                    liveIDs.append(id)
                } else if let mapped = placeholderMap[id] {
                    liveIDs.append(mapped)
                } else if id.hasPrefix("POWAY-") || id.hasPrefix("84-105-") {
                    if !availableExternals.isEmpty {
                        let nextExt = availableExternals.removeFirst()
                        placeholderMap[id] = nextExt
                        liveIDs.append(nextExt)
                    }
                }
            }

            guard !liveIDs.isEmpty else { continue }
            tokens[idIdx] = "id:" + liveIDs.joined(separator: "+")
            resolvedSegments.append("\"" + tokens.joined(separator: " ") + "\"")
        }

        guard !resolvedSegments.isEmpty else { return raw }
        return "displayplacer " + resolvedSegments.joined(separator: " ")
    }

    func buildRoleDraftCommand() -> String {
        guard !connected.isEmpty else { return "" }
        let mainDisplay = connected.first(where: { roleDraft[$0.id] == .main })
            ?? connected.first(where: { roleDraft[$0.id] != .off })
            ?? connected[0]

        let mirrors = connected.filter { $0.id != mainDisplay.id && roleDraft[$0.id] == .mirrorMain }
        let lefts = connected.filter { $0.id != mainDisplay.id && roleDraft[$0.id] == .extendLeft }
        let rights = connected.filter { $0.id != mainDisplay.id && roleDraft[$0.id] == .extendRight }
        let offs = connected.filter { roleDraft[$0.id] == .off && $0.id != mainDisplay.id }

        var args: [String] = []
        let mainGroupIDs = ([mainDisplay.id] + mirrors.map(\.id)).joined(separator: "+")
        if !mirrors.isEmpty {
            args.append(#""id:\#(mainGroupIDs) res:1920x1080 enabled:true scaling:off origin:(0,0) degree:0""#)
        } else {
            let res = mainDisplay.isBuiltIn ? "1728x1117" : "1920x1080"
            let scale = mainDisplay.isBuiltIn ? "on" : "off"
            args.append(#""id:\#(mainDisplay.id) res:\#(res) enabled:true scaling:\#(scale) origin:(0,0) degree:0""#)
        }

        var leftX = 0
        for d in lefts {
            let w = d.isBuiltIn ? 1728 : 1920
            let res = d.isBuiltIn ? "1728x1117" : "1920x1080"
            let scale = d.isBuiltIn ? "on" : "off"
            leftX -= w
            args.append(#""id:\#(d.id) res:\#(res) enabled:true scaling:\#(scale) origin:(\#(leftX),0) degree:0""#)
        }

        var rightX = (!mirrors.isEmpty || !mainDisplay.isBuiltIn) ? 1920 : 1728
        for d in rights {
            let w = d.isBuiltIn ? 1728 : 1920
            let res = d.isBuiltIn ? "1728x1117" : "1920x1080"
            let scale = d.isBuiltIn ? "on" : "off"
            args.append(#""id:\#(d.id) res:\#(res) enabled:true scaling:\#(scale) origin:(\#(rightX),0) degree:0""#)
            rightX += w
        }

        for d in offs {
            args.append(#""id:\#(d.id) enabled:false""#)
        }

        return "displayplacer " + args.joined(separator: " ")
    }

    func applyPreset(_ preset: DisplayPreset) {
        let cmd = resolveCommand(preset.command)
        guard !cmd.isEmpty else { return }
        executeDisplayplacerCommand(cmd, presetID: preset.id, label: preset.name)
    }

    func applyRoleDraft() {
        let cmd = buildRoleDraftCommand()
        guard !cmd.isEmpty else { return }
        executeDisplayplacerCommand(cmd, presetID: nil, label: "Custom Display Roles")
    }

    func executeDisplayplacerCommand(_ cmd: String, presetID: String?, label: String) {
        busy = true
        errorMessage = nil
        statusMessage = "Applying \(label)…"
        Task {
            let (rc, out, err) = await Task.detached {
                DisplayStore.runCommand("/bin/zsh", ["-c", cmd])
            }.value
            self.busy = false
            let combined = (out + "\n" + err).trimmingCharacters(in: .whitespacesAndNewlines)
            if rc == 0 || !combined.localizedCaseInsensitiveContains("error") {
                if let pid = presetID {
                    self.root.lastAppliedPresetID = pid
                    self.save()
                }
                self.statusMessage = "Applied: \(label)"
            } else {
                self.errorMessage = "Warning applying \(label): \(combined)"
            }
            try? await Task.sleep(nanoseconds: 700_000_000)
            self.refreshDisplays()
        }
    }

    // MARK: - Space, Monitor History & Preset CRUD

    func addFolder(name: String, description: String) {
        let clean = name.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !clean.isEmpty else { return }
        let id = clean.lowercased().replacingOccurrences(of: " ", with: "-") + "-\(Int(Date().timeIntervalSince1970) % 10000)"
        let sig = connected.filter { !$0.isBuiltIn }.map(\.id)
        var aliases: [String: String] = [:]
        var mons: [MonitorRecord] = []
        for d in connected {
            aliases[d.id] = d.name
            mons.append(MonitorRecord(
                id: d.id,
                label: d.name,
                note: d.isBuiltIn ? "Built-in" : "\(d.resolution) @ \(d.hz)Hz",
                icon: d.isBuiltIn ? "laptopcomputer" : "display",
                ignoredInSpace: false
            ))
        }
        let newFolder = MachineFolder(
            id: id,
            name: clean,
            description: description.isEmpty ? "Monitors & presets for \(clean)" : description,
            signatureUUIDs: sig,
            displayAliases: aliases,
            monitors: mons,
            presets: []
        )
        root.folders.append(newFolder)
        root.selectedFolderID = id
        save()
    }

    func updateFolder(id: String, name: String, description: String) {
        guard let idx = root.folders.firstIndex(where: { $0.id == id }) else { return }
        let cleanName = name.trimmingCharacters(in: .whitespacesAndNewlines)
        if !cleanName.isEmpty {
            root.folders[idx].name = cleanName
        }
        root.folders[idx].description = description.trimmingCharacters(in: .whitespacesAndNewlines)
        save()
    }

    func keepOnlyFolder(id: String) {
        guard let target = root.folders.first(where: { $0.id == id }) else { return }
        root.folders = [target]
        root.selectedFolderID = target.id
        save()
        statusMessage = "Single-space mode: kept only '\(target.name)'"
    }

    func deleteFolder(id: String) {
        root.folders.removeAll { $0.id == id }
        if root.selectedFolderID == id, let first = root.folders.first {
            root.selectedFolderID = first.id
        }
        save()
    }

    func upsertMonitor(inFolder folderID: String, record: MonitorRecord) {
        guard let idx = root.folders.firstIndex(where: { $0.id == folderID }) else { return }
        var mons = root.folders[idx].resolvedMonitors
        if let mIdx = mons.firstIndex(where: { $0.id == record.id }) {
            mons[mIdx] = record
        } else {
            mons.append(record)
        }
        root.folders[idx].monitors = mons
        root.folders[idx].displayAliases[record.id] = record.label
        save()
    }

    func deleteMonitor(inFolder folderID: String, monitorID: String) {
        guard let idx = root.folders.firstIndex(where: { $0.id == folderID }) else { return }
        var mons = root.folders[idx].resolvedMonitors
        mons.removeAll { $0.id == monitorID }
        root.folders[idx].monitors = mons
        root.folders[idx].displayAliases.removeValue(forKey: monitorID)
        save()
    }

    func saveNewPreset(inFolder folderID: String, name: String, subtitle: String, command: String) {
        guard let idx = root.folders.firstIndex(where: { $0.id == folderID }) else { return }
        let cleanName = name.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !cleanName.isEmpty, !command.isEmpty else { return }
        let preset = DisplayPreset(
            id: "\(folderID)-\(Int(Date().timeIntervalSince1970))",
            name: cleanName,
            subtitle: subtitle.isEmpty ? "Custom display preset" : subtitle,
            icon: command.contains("+") ? "rectangle.on.rectangle.circle.fill" : "rectangle.split.3x1.fill",
            command: command
        )
        root.folders[idx].presets.append(preset)
        save()
        statusMessage = "Saved '\(cleanName)' to \(root.folders[idx].name)"
    }

    func updatePreset(folderID: String, presetID: String, name: String, subtitle: String, icon: String, command: String) {
        guard let fIdx = root.folders.firstIndex(where: { $0.id == folderID }),
              let pIdx = root.folders[fIdx].presets.firstIndex(where: { $0.id == presetID }) else { return }
        root.folders[fIdx].presets[pIdx].name = name.trimmingCharacters(in: .whitespacesAndNewlines)
        root.folders[fIdx].presets[pIdx].subtitle = subtitle.trimmingCharacters(in: .whitespacesAndNewlines)
        root.folders[fIdx].presets[pIdx].icon = icon
        root.folders[fIdx].presets[pIdx].command = command.trimmingCharacters(in: .whitespacesAndNewlines)
        save()
        statusMessage = "Updated preset '\(name)'"
    }

    func overwritePresetWithCurrent(folderID: String, presetID: String) {
        guard !currentCommand.isEmpty,
              let fIdx = root.folders.firstIndex(where: { $0.id == folderID }),
              let pIdx = root.folders[fIdx].presets.firstIndex(where: { $0.id == presetID }) else { return }
        root.folders[fIdx].presets[pIdx].command = currentCommand
        save()
        statusMessage = "Updated '\(root.folders[fIdx].presets[pIdx].name)' with current layout"
    }

    func movePreset(fromFolderID: String, presetID: String, toFolderID: String) {
        guard fromFolderID != toFolderID,
              let fromIdx = root.folders.firstIndex(where: { $0.id == fromFolderID }),
              let toIdx = root.folders.firstIndex(where: { $0.id == toFolderID }),
              let pIdx = root.folders[fromIdx].presets.firstIndex(where: { $0.id == presetID }) else { return }
        let preset = root.folders[fromIdx].presets.remove(at: pIdx)
        root.folders[toIdx].presets.append(preset)
        save()
    }

    func deletePreset(folderID: String, presetID: String) {
        guard let fIdx = root.folders.firstIndex(where: { $0.id == folderID }) else { return }
        root.folders[fIdx].presets.removeAll { $0.id == presetID }
        save()
    }
}

// MARK: - Monitor Badge Resolution

struct PresetMonitorBadge: Identifiable, Equatable {
    let id: String
    let name: String
    let icon: String
    let roleLabel: String
    let roleColor: Color
}

extension DisplayStore {
    func monitorRecord(for uuid: String, in folder: MachineFolder) -> MonitorRecord {
        if let rec = folder.resolvedMonitors.first(where: { $0.id == uuid }) {
            return rec
        }
        let raw = folder.displayAliases[uuid]
            ?? connected.first(where: { $0.id == uuid })?.name
            ?? (uuid == SeedData.mbpUUID ? "MacBook" : "Monitor")
        let lower = raw.lowercased()
        let icon: String
        if lower.contains("macbook") || lower.contains("laptop") || uuid == SeedData.mbpUUID {
            icon = "laptopcomputer"
        } else if lower.contains("tv") || lower.contains("blackmagic") || lower.contains("extron") || lower.contains("broadcast") || lower.contains("proj") {
            icon = "tv.fill"
        } else {
            icon = "display"
        }
        return MonitorRecord(id: uuid, label: raw, note: "", icon: icon, ignoredInSpace: false)
    }

    func monitorBadges(for preset: DisplayPreset, in folder: MachineFolder) -> [PresetMonitorBadge] {
        let cmd = preset.command.trimmingCharacters(in: .whitespacesAndNewlines)
        let visibleMons = folder.resolvedMonitors.filter { !$0.ignoredInSpace }

        if cmd.hasPrefix("@dynamic:") {
            let mode = cmd.replacingOccurrences(of: "@dynamic:", with: "")
            let firstLabel = visibleMons.first?.label ?? "Primary"
            let firstIcon = visibleMons.first?.icon ?? "laptopcomputer"
            let secondLabel = visibleMons.dropFirst().first?.label ?? "Room TV"
            let secondIcon = visibleMons.dropFirst().first?.icon ?? "tv.fill"
            switch mode {
            case "mirror_all":
                return [
                    PresetMonitorBadge(id: "dyn-1", name: firstLabel, icon: firstIcon, roleLabel: "MAIN", roleColor: .blue),
                    PresetMonitorBadge(id: "dyn-2", name: secondLabel, icon: secondIcon, roleLabel: "MIRROR", roleColor: .green),
                ]
            case "extend_all":
                return [
                    PresetMonitorBadge(id: "dyn-1", name: firstLabel, icon: firstIcon, roleLabel: "MAIN", roleColor: .blue),
                    PresetMonitorBadge(id: "dyn-2", name: secondLabel, icon: secondIcon, roleLabel: "EXTEND", roleColor: .purple),
                ]
            case "broadcast_main_extend_builtin":
                return [
                    PresetMonitorBadge(id: "dyn-2", name: secondLabel, icon: secondIcon, roleLabel: "MAIN", roleColor: .blue),
                    PresetMonitorBadge(id: "dyn-1", name: firstLabel, icon: firstIcon, roleLabel: "EXTEND", roleColor: .purple),
                ]
            case "laptop_only":
                return [
                    PresetMonitorBadge(id: "dyn-1", name: firstLabel, icon: firstIcon, roleLabel: "MAIN", roleColor: .blue),
                    PresetMonitorBadge(id: "dyn-2", name: secondLabel, icon: secondIcon, roleLabel: "OFF", roleColor: .secondary),
                ]
            default:
                return []
            }
        }

        var badges: [PresetMonitorBadge] = []
        let pattern = #""([^"]+)""#
        guard let regex = try? NSRegularExpression(pattern: pattern) else { return [] }
        let nsRange = NSRange(cmd.startIndex..<cmd.endIndex, in: cmd)
        let matches = regex.matches(in: cmd, range: nsRange)

        for (segIdx, m) in matches.enumerated() {
            guard let r = Range(m.range(at: 1), in: cmd) else { continue }
            let seg = String(cmd[r])
            var idPart = ""
            var originX = 0
            var isOff = seg.localizedCaseInsensitiveContains("enabled:false")

            for tok in seg.split(separator: " ") {
                let s = String(tok)
                if s.hasPrefix("id:") {
                    idPart = s.replacingOccurrences(of: "id:", with: "")
                } else if s.hasPrefix("origin:(") {
                    let coords = s.replacingOccurrences(of: "origin:(", with: "").replacingOccurrences(of: ")", with: "")
                    if let firstNum = coords.split(separator: ",").first, let xVal = Int(firstNum) {
                        originX = xVal
                    }
                } else if s == "enabled:false" {
                    isOff = true
                }
            }

            let rawUUIDs = idPart.split(separator: "+").map(String.init)
            // Filter out monitors marked ignoredInSpace (e.g. MacBook in a separate room in 84-101)
            let visibleUUIDs = rawUUIDs.filter { !monitorRecord(for: $0, in: folder).ignoredInSpace }
            let isMainGroup = !isOff && (originX == 0 && segIdx == 0)

            for (uIdx, uuid) in visibleUUIDs.enumerated() {
                let rec = monitorRecord(for: uuid, in: folder)
                let roleLabel: String
                let roleColor: Color
                if isOff {
                    roleLabel = "OFF"
                    roleColor = .secondary
                } else if isMainGroup {
                    if uIdx == 0 {
                        roleLabel = "MAIN"
                        roleColor = .blue
                    } else {
                        roleLabel = "MIRROR"
                        roleColor = .green
                    }
                } else if visibleUUIDs.count > 1 && uIdx > 0 {
                    roleLabel = "MIRROR"
                    roleColor = .green
                } else if originX < 0 {
                    roleLabel = "EXT LEFT"
                    roleColor = .purple
                } else {
                    roleLabel = "EXTEND"
                    roleColor = .purple
                }
                badges.append(PresetMonitorBadge(
                    id: "\(preset.id)-\(uuid)-\(segIdx)-\(uIdx)",
                    name: rec.label,
                    icon: rec.icon,
                    roleLabel: roleLabel,
                    roleColor: roleColor
                ))
            }
        }
        return badges
    }
}

